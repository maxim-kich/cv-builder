import { EventEmitter } from "node:events";
import { expect, it, vi } from "vitest";
const processes = vi.hoisted(() => ({ children: [] as Array<any> }));
vi.mock("node:child_process", () => ({ spawn: vi.fn(() => {
  const child = new EventEmitter() as any;
  child.stdout = new EventEmitter();
  child.stderr = { resume: vi.fn() };
  child.stdin = Object.assign(new EventEmitter(), { end: vi.fn() });
  child.kill = vi.fn();
  processes.children.push(child);
  return child;
}) }));
import { renderTemplate } from "../server/template/render";
import { createEmptyResume } from "../src/cvStore";
it("kills obsolete workers and starts queued renders only after a cancelled worker exits", async () => {
  const template = { id: "t", title: "t", source: "", fonts: [], revision: 1, createdAt: "", updatedAt: "" };
  const a = new AbortController();
  const b = new AbortController();
  const first = renderTemplate(template, createEmptyResume(), true, a.signal).catch(error => error);
  const second = renderTemplate(template, createEmptyResume(), true, b.signal).catch(error => error);
  await vi.waitFor(() => expect(processes.children).toHaveLength(2));
  const queued = renderTemplate(template, createEmptyResume());
  a.abort(); b.abort();
  expect(processes.children[0].kill).toHaveBeenCalledWith("SIGKILL");
  expect(processes.children[1].kill).toHaveBeenCalledWith("SIGKILL");
  await Promise.resolve();
  expect(processes.children).toHaveLength(2);
  processes.children[0].emit("close");
  await vi.waitFor(() => expect(processes.children).toHaveLength(3));
  processes.children[1].emit("close");
  const latest = processes.children[2];
  latest.stdout.emit("data", '\nCV_TEMPLATE_RESULT:' + JSON.stringify({ pdf: Buffer.from("PDF latest").toString("base64"), report: { status: "passed", pages: 1, missingText: [], warnings: [] } }));
  latest.emit("close");
  expect((await first).message).toContain("cancelled");
  expect((await second).message).toContain("cancelled");
  expect((await queued).pdf.toString()).toBe("PDF latest");
});
it("removes cancelled queued drafts without spawning a worker", async () => {
  const { acquireRenderSlot } = await import("../server/template/slots");
  const releaseA = await acquireRenderSlot();
  const releaseB = await acquireRenderSlot();
  const controller = new AbortController();
  const obsolete = acquireRenderSlot(controller.signal).catch(error => error);
  controller.abort();
  expect((await obsolete).message).toContain("cancelled");
  releaseA(); releaseB();
  const release = await acquireRenderSlot();
  release();
});
